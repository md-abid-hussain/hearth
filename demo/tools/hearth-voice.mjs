// Speaks a line in Hearth's own voice (AssemblyAI text-to-speech, the voice the app uses) and
// saves public/voice/<name>.wav plus video/levels/<name>.ts, a per-frame loudness track that
// moves Hearth's mouth in the video.
//
//   node tools/hearth-voice.mjs hearth-intro "Oh, hi there. I'm Hearth."
//
// Reads ASSEMBLYAI_API_KEY (and HEARTH_TTS_VOICE, if set) from the .env Hearth uses.
import { createRequire } from 'module'
import { mkdirSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const wisp = join(root, '..', 'wisp')
const require = createRequire(join(wisp, 'package.json'))
const { AssemblyAI } = require('assemblyai')
// The same places Hearth looks for its .env: the app folder and the folder above it.
for (const dir of [wisp, join(wisp, '..')]) require('dotenv').config({ path: join(dir, '.env'), quiet: true })

const SAMPLE_RATE = 24_000
const FPS = 30
const [name, ...words] = process.argv.slice(2)
const text = words.join(' ')
if (!name || !text) throw new Error('usage: node tools/hearth-voice.mjs <name> "<text>"')
if (!process.env.ASSEMBLYAI_API_KEY) throw new Error('ASSEMBLYAI_API_KEY is not set in .env')

const client = new AssemblyAI({ apiKey: process.env.ASSEMBLYAI_API_KEY })
const session = client.tts.session({
  voiceId: process.env.HEARTH_TTS_VOICE || 'aai-kyla',
  sampleRate: SAMPLE_RATE,
  encoding: 'pcm_s16le',
  wordBoundaries: false,
  connectTimeout: 15_000
})
await session.connect()
session.generate(text)
const request = session.flush()
const chunks = []
for await (const pcm of session.audio(request)) chunks.push(Buffer.from(pcm))
await session.close()
const pcm = Buffer.concat(chunks)

const header = Buffer.alloc(44)
header.write('RIFF', 0)
header.writeUInt32LE(36 + pcm.length, 4)
header.write('WAVEfmt ', 8)
header.writeUInt32LE(16, 16)
header.writeUInt16LE(1, 20)
header.writeUInt16LE(1, 22)
header.writeUInt32LE(SAMPLE_RATE, 24)
header.writeUInt32LE(SAMPLE_RATE * 2, 28)
header.writeUInt16LE(2, 32)
header.writeUInt16LE(16, 34)
header.write('data', 36)
header.writeUInt32LE(pcm.length, 40)
mkdirSync(join(root, 'public', 'voice'), { recursive: true })
writeFileSync(join(root, 'public', 'voice', `${name}.wav`), Buffer.concat([header, pcm]))

// Loudness per video frame, scaled so normal speech reaches about 1, then lightly smoothed.
const perFrame = SAMPLE_RATE / FPS
const rms = []
for (let start = 0; start < pcm.length / 2; start += perFrame) {
  let sum = 0
  let n = 0
  for (let i = start; i < Math.min(start + perFrame, pcm.length / 2); i++) {
    const v = pcm.readInt16LE(i * 2) / 32768
    sum += v * v
    n++
  }
  rms.push(Math.sqrt(sum / Math.max(1, n)))
}
const loud = [...rms].sort((a, b) => a - b)[Math.floor(rms.length * 0.9)] || 1
let prev = 0
const levels = rms.map((r) => {
  const v = Math.min(1, r / loud)
  prev = prev + (v - prev) * 0.6
  return Math.round(prev * 100) / 100
})
mkdirSync(join(root, 'video', 'levels'), { recursive: true })
writeFileSync(
  join(root, 'video', 'levels', `${name}.ts`),
  `// Generated by tools/hearth-voice.mjs: loudness of public/voice/${name}.wav per frame at ${FPS} fps.\n` +
    `export const text = ${JSON.stringify(text)}\n` +
    `export const levels: number[] = ${JSON.stringify(levels)}\n`
)
console.log(`${name}: ${(pcm.length / 2 / SAMPLE_RATE).toFixed(2)} s, ${levels.length} frames`)

// Writes video/levels/<name>.ts: the per-frame loudness of an audio file (any format ffmpeg
// reads), so Hearth's face can follow a voice in the video, plus the line's text.
//
//   node tools/levels.mjs public/voice/u-howami.mp3 u-howami "Hearth, how am I doing?"
import { spawnSync } from 'child_process'
import { mkdirSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
import ffmpeg from 'ffmpeg-static'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SAMPLE_RATE = 24_000
const FPS = 30
const [file, name, ...words] = process.argv.slice(2)
if (!file || !name) throw new Error('usage: node tools/levels.mjs <audio file> <name> "<text>"')

const decoded = spawnSync(ffmpeg, ['-v', 'error', '-i', file, '-ac', '1', '-ar', String(SAMPLE_RATE), '-f', 's16le', '-'], {
  maxBuffer: 1 << 28
})
if (decoded.status !== 0) throw new Error(`ffmpeg could not read ${file}: ${decoded.stderr}`)
const pcm = decoded.stdout

const perFrame = SAMPLE_RATE / FPS
const rms = []
for (let start = 0; start < pcm.length / 2; start += perFrame) {
  let sum = 0
  let n = 0
  for (let i = start; i < Math.min(start + perFrame, pcm.length / 2); i++) {
    const v = pcm.readInt16LE(i * 2) / 32768
    sum += v * v
    n++
  }
  rms.push(Math.sqrt(sum / Math.max(1, n)))
}
const loud = [...rms].sort((a, b) => a - b)[Math.floor(rms.length * 0.9)] || 1
let prev = 0
const levels = rms.map((r) => {
  prev = prev + (Math.min(1, r / loud) - prev) * 0.6
  return Math.round(prev * 100) / 100
})
mkdirSync(join(root, 'video', 'levels'), { recursive: true })
writeFileSync(
  join(root, 'video', 'levels', `${name}.ts`),
  `// Generated by tools/levels.mjs: loudness of ${file.replace(/\\/g, '/')} per frame at ${FPS} fps.\n` +
    `export const text = ${JSON.stringify(words.join(' '))}\n` +
    `export const levels: number[] = ${JSON.stringify(levels)}\n`
)
console.log(`${name}: ${(pcm.length / 2 / SAMPLE_RATE).toFixed(2)} s, ${levels.length} frames`)
